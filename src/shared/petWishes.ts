/** Stable across both clients; a phrase changes only every 30 game minutes. */
export function petWish(state: GameState, id: PetId): PetWish {
  const pet = state.pets[id];
  const hungry = pet.satiety < 35;
  const hasFood = state.petBowls[id] > 0;
  const routine = pet.routine?.kind;
  if(routine==='come')return {kind:'affection',title:'🐾 Идёт на зов',
    message:PETS[id].name+' обходит мебель и направляется к хозяину.',
    advice:'Дай питомцу добраться самостоятельно',urgent:false};
  if(routine==='fetch'&&id==='verdell')return {kind:'play',title:'🎾 Несёт мяч',
    message:'Верделл бежит к мячу и возвращается с ним к хозяину.',
    advice:'Подожди, пока Верделл принесёт игрушку',urgent:false};
  if(routine==='perch'&&id==='simba')return {kind:'rest',title:'🛋️ Любимое местечко',
    message:'Симба выбирает удобную подушку и устраивается на ней.',
    advice:'Можно наблюдать за отдыхом кота',urgent:false};
  let kind: PetWishKind;
  if (routine === 'eat') kind = 'eating';
  else if (pet.satiety < 20) kind = hasFood ? 'hungryReady' : 'hungryEmpty';
  else if (routine === 'sleep') kind = 'sleeping';
  else if (routine === 'toilet') kind = 'toilet';
  else if (pet.bladder < 25) kind = 'needsToilet';
  else if (pet.energy < 32) kind = 'rest';
  else if (hungry) kind = hasFood ? 'hungryReady' : 'hungry';
  else if (pet.happiness < 44) kind = 'play';
  else if (pet.bond < 24) kind = 'affection';
  else if (routine === 'wander') kind = 'wander';
  else if (pet.happiness > 78 && pet.bond > 52) kind = 'content';
  else kind = 'curious';

  const variants = phrases[id][kind];
  const block = Math.floor((state.clock.day * 1440 + state.clock.minute) / 30);
  const index = ((block + (id === 'simba' ? 3 : 0)) % variants.length + variants.length) % variants.length;
  const [title, advice] = titles[kind];
  return { kind, title, advice, message: variants[index],
    urgent: kind === 'hungryEmpty' && pet.satiety < 20 };
}

export function petWishText(state: GameState, id: PetId): string {
  const wish = petWish(state, id);
  return `${PETS[id].name}: ${wish.title} — ${wish.message}`;
}
