export function pendingHomeQuest(shift:ShiftAssignment|undefined,now:number){return shift?.quests?.find(q=>!q.result&&q.at<=now&&now<q.until);}
export function homeQuestContent(shift:ShiftAssignment,run:HomeQuestRun):HomeQuest|undefined {return HOME_QUESTS[shift.job as HomeJobId]?.[run.index];}
export function validHomeQuests(shift:Record<string,unknown>):boolean {if(shift.quests===undefined)return true;const pool=HOME_QUESTS[shift.job as HomeJobId];if(!pool||!Array.isArray(shift.quests)||shift.quests.length!==2)return false;const seen=new Set<number>(),nonces=new Set<string>();let end=Number(shift.startedAt);for(const q of shift.quests){if(!q||typeof q.nonce!=="string"||q.nonce.length!==36||nonces.has(q.nonce)||!Number.isInteger(q.index)||!pool[q.index]||seen.has(q.index)||!Number.isInteger(q.at)||!Number.isInteger(q.until)||q.at<end||q.until<=q.at||q.until>Number(shift.endsAt)||!Array.isArray(q.order)||q.order.length!==3||!q.order.every((n:unknown)=>Number.isInteger(n))||[...q.order].sort().join(",")!=="0,1,2"||(q.result!==undefined&&!["correct","wrong","skipped"].includes(q.result)))return false;seen.add(q.index);nonces.add(q.nonce);end=q.until;}return true;}
