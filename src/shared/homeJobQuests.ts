export function pendingHomeQuest(shift:ShiftAssignment|undefined,now:number){return shift?.quests?.find(q=>!q.result&&q.at<=now&&now<q.until);}
export function homeQuestContent(shift:ShiftAssignment,run:HomeQuestRun):HomeQuest|undefined {return HOME_QUESTS[shift.job as HomeJobId]?.[run.index];}

export function validQuestChoice(spec:HomeQuest,run:HomeQuestRun,choice:unknown):choice is number{
 if(choice===-1)return true;
 if(typeof choice!=='number'||!Number.isSafeInteger(choice))return false;
 return spec.kind==='multi'?choice>100&&choice<100+(1<<run.order.length):choice>=0&&choice<run.order.length;
}
export function correctQuestChoice(spec:HomeQuest,run:HomeQuestRun):number{
 if(spec.kind!=='multi')return run.order.indexOf(spec.answer);
 return 100+run.order.reduce((mask,key,i)=>mask|((spec.answers??[]).includes(key)?1<<i:0),0);
}
export function validHomeQuests(shift:Record<string,unknown>):boolean{
 if(shift.quests===undefined)return true;
 const pool=HOME_QUESTS[shift.job as HomeJobId];
 if(!pool||!Array.isArray(shift.quests)||![2,3,4,5].includes(shift.quests.length))return false;
 const seen=new Set<number>(),nonces=new Set<string>();let end=Number(shift.startedAt);
 for(const q of shift.quests){
  if(!q||typeof q.nonce!=="string"||q.nonce.length!==36||nonces.has(q.nonce)||!Number.isInteger(q.index)||!pool[q.index]||seen.has(q.index)||!Number.isInteger(q.at)||!Number.isInteger(q.until)||q.at<end||q.until<=q.at||q.until>Number(shift.endsAt)||!Array.isArray(q.order)||q.order.length!==pool[q.index].options.length||!q.order.every((n:unknown)=>Number.isInteger(n))||[...q.order].sort().join(",")!==pool[q.index].options.map((_,i)=>i).join(",")||(q.result!==undefined&&!["correct","wrong","skipped"].includes(q.result)))return false;
  seen.add(q.index);nonces.add(q.nonce);end=q.until;
 }
 return true;
}
