export const MEDIA_CATALOG:readonly MediaTitle[]=[...films.map(([id,title,year,genre,description])=>({id,title,year,genre,description})),...series.map(([id,title,year,genre,description,seasons])=>({id,title,year,genre,description,seasons}))];
const catalog=new Map(MEDIA_CATALOG.map(t=>[t.id,t]));
export const mediaTitle=(id:unknown)=>typeof id==='string'?catalog.get(id):undefined;
export type MediaSelection={id:string;season?:number;episode?:number};
export function validSelection(value:unknown,genre?:Genre):value is MediaSelection{
 if(!value||typeof value!=='object'||Array.isArray(value))return false;
 const s=value as MediaSelection,t=mediaTitle(s.id);if(!t||genre&&t.genre!==genre)return false;
 if(!t.seasons)return s.season===undefined&&s.episode===undefined;
 return Number.isInteger(s.season)&&Number.isInteger(s.episode)&&s.season!>=1&&s.season!<=t.seasons.length&&s.episode!>=1&&s.episode!<=t.seasons[s.season!-1];
}
export function mediaLabel(s:MediaSelection){return mediaTitle(s.id)!.title+(s.season?' · С'+s.season+' Э'+s.episode:'');}
export function nextEpisode(s:MediaSelection):MediaSelection|undefined{const t=mediaTitle(s.id);if(!t?.seasons||!validSelection(s))return;const season=s.season!,episode=s.episode!;if(episode<t.seasons[season-1])return {id:s.id,season,episode:episode+1};if(season<t.seasons.length)return {id:s.id,season:season+1,episode:1};}
