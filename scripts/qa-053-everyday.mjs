import {chromium} from 'playwright';
import {mkdtempSync,mkdirSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import {once} from 'node:events';
import assert from 'node:assert/strict';
import WebSocket from 'ws';
import {initialState,points} from '../src/shared/protocol.ts';
import {openServerFiles} from '../server/storage.ts';
import {startServer} from '../server/server.ts';
const out='/tmp/simlife-053-everyday';mkdirSync(out,{recursive:true});
const dir=mkdtempSync(join(tmpdir(),'everyday-053-'));let browser,server,peer,page;
try{
 const s=initialState();s.clock.minute=780;s.money=100000;s.pantry.coffeeNescafeGold=2;
 for(const role of ['vlad','alina'])Object.assign(s.characters[role],{hunger:95,energy:75,hygiene:95,bladder:95,fun:95,comfort:95,social:95,pose:'idle'});
 Object.assign(s.characters.vlad,points.desk);Object.assign(s.characters.alina,points.coffeeMaker);
 const files=openServerFiles(dir);files.save(s);
 server=await startServer({port:0,host:'127.0.0.1',dataDir:dir,distDir:resolve('dist'),testNoCodes:true,taskTimeScale:1,autonomyTiming:{idleMs:2500,careCooldownMs:3500,leisureCooldownMs:4500}});
 browser=await chromium.launch({headless:true,args:['--enable-webgl','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--disable-dev-shm-usage']});
 page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 page.on('console',m=>{if(m.type()==='error'&&/shader|webgl|three/i.test(m.text()))errors.push(m.text());});
 await page.addInitScript(()=>{const Native=window.WebSocket;window.__qaPackets=[];window.WebSocket=class extends Native{constructor(...a){super(...a);window.__qaSocket=this;this.addEventListener('message',e=>{try{window.__qaPackets.push(JSON.parse(e.data));}catch{}});}};});
 const shot=name=>page.screenshot({path:join(out,name+'.jpg'),type:'jpeg',quality:92});
 const send=message=>page.evaluate(m=>window.__qaSocket.send(JSON.stringify(m)),message);
 const waitVisual=fn=>page.waitForFunction(fn,undefined,{timeout:45000});
 await page.goto('http://127.0.0.1:'+server.port+'/?cameraQA=1',{waitUntil:'domcontentloaded',timeout:60000});
 await page.locator('.enter-button').waitFor({timeout:60000});await page.waitForFunction(()=>!document.querySelector('.enter-button')?.disabled,undefined,{timeout:70000});
 await page.locator('[data-role=alina]').first().click();await page.locator('.enter-button').click();await page.locator('#auth').waitFor({state:'hidden',timeout:30000});
 peer=new WebSocket('ws://127.0.0.1:'+server.port+'/sync');const packets=[];
 peer.on('message',raw=>packets.push(JSON.parse(raw.toString())));await once(peer,'open');
 peer.send(JSON.stringify({type:'auth',role:'vlad',code:files.access.vlad}));
 const take=async(type,predicate=()=>true)=>{for(let i=0;i<1200;i++){const p=packets.find(x=>x.type===type&&predicate(x));if(p)return p;await new Promise(r=>setTimeout(r,40));}throw Error('Missing '+type);};
 await take('ready');peer.send(JSON.stringify({type:'job_start',job:'vibeSite',device:'desktop'}));
 const work=await take('snapshot',p=>p.state.activeShifts.vlad?.job==='vibeSite'&&p.state.characters.vlad.pose==='work');
 const shift=work.state.activeShifts.vlad;
 await page.locator('#camera-follow').tap();await send({type:'autonomy_mode',mode:'full'});
 const task=await take('task_started',p=>p.role==='alina'&&p.command?.type==='serve_work_coffee');
 assert.equal(task.home.station,'workCoffee');
 await waitVisual(()=>JSON.parse(document.querySelector('#game-canvas').dataset.yardQA).actors.alina.activity==='coffee');
 await shot('01-brew');
 await waitVisual(()=>{const a=JSON.parse(document.querySelector('#game-canvas').dataset.yardQA).actors.alina;return a.coffee.visible&&!a.coffee.offering;});
 await shot('02-carry');
 await waitVisual(()=>{const d=JSON.parse(document.querySelector('#game-canvas').dataset.yardQA);return d.actors.alina.coffee.visible&&d.actors.alina.coffee.offering&&d.actors.vlad.pose==='work';});
 await page.locator('#showcase-toggle').tap();await page.locator('[data-showcase=alina]').tap();await page.waitForTimeout(500);
 await shot('03-delivery');
 const delivered=await take('snapshot',p=>p.state.activeShifts.vlad?.coffeeServed===true);
 assert.equal(delivered.state.pantry.coffeeNescafeGold,1);assert.equal(delivered.state.money,100000);
 assert.equal(delivered.state.activeShifts.vlad.endsAt,shift.endsAt);assert.equal(delivered.state.activeShifts.vlad.targetPay,shift.targetPay);
 assert.equal(delivered.state.characters.vlad.pose,'work');
 await send({type:'autonomy_mode',mode:'off'});
 await waitVisual(()=>{const d=JSON.parse(document.querySelector('#game-canvas').dataset.yardQA);return d.workCoffeeDesk&&!d.actors.alina.coffee.visible&&d.actors.vlad.pose==='work';});
 await page.locator('#showcase-toggle').tap();await page.locator('[data-showcase=vlad]').tap();await page.waitForTimeout(1000);await shot('04-desk-after');
 assert.deepEqual(errors,[]);console.log('WORK_COFFEE_QA',await page.locator('#game-canvas').evaluate(el=>JSON.parse(el.dataset.yardQA)));
}catch(e){console.error('QA failure',e);if(page){console.error(await page.evaluate(()=>({qa:document.querySelector('#game-canvas')?.dataset.yardQA,packets:window.__qaPackets?.filter(m=>['task_started','task_ended','error'].includes(m.type)).slice(-8)})).catch(()=>null));await page.screenshot({path:join(out,'failure.jpg')}).catch(()=>{});}throw e;
}finally{peer?.terminate();await browser?.close();await server?.close();rmSync(dir,{recursive:true,force:true});}
