import {chromium} from 'playwright';
import {mkdtempSync,mkdirSync,rmSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
import WebSocket from 'ws';
import {once} from 'node:events';
import {initialState} from '../src/shared/protocol.ts';
import {stationById,approachFor} from '../src/shared/locations.ts';
import {openServerFiles} from '../server/storage.ts';
import {startServer} from '../server/server.ts';
const mode=process.argv[2]??'market',out='/tmp/simlife-car-055-'+mode;
mkdirSync(out,{recursive:true});
const dir=mkdtempSync(join(tmpdir(),'car-055-'));let browser,server,buddy,page;
try{
 const s=initialState();s.clock.minute=mode==='lake'?1270:720;s.money=100000;s.autonomy={vlad:'off',alina:'off'};
 Object.assign(s.characters.vlad,approachFor(stationById('home','family-car'),'vlad'));
 Object.assign(s.characters.alina,approachFor(stationById('home','family-car'),'alina'));
 openServerFiles(dir).save(s);
 server=await startServer({port:0,host:'127.0.0.1',dataDir:dir,distDir:resolve('dist'),testNoCodes:true,lifeClock:{now:()=>0,tickMs:600000}});
 const buddyPackets=[];buddy=new WebSocket('ws://127.0.0.1:'+server.port+'/sync');
 buddy.on('message',x=>{try{buddyPackets.push(JSON.parse(x.toString()));}catch{}});
 await once(buddy,'open');buddy.send(JSON.stringify({type:'auth',role:'alina',code:'TEST-LOCAL-NO-CODES'}));
 browser=await chromium.launch({headless:true,args:['--enable-webgl','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--disable-dev-shm-usage']});
 page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error'&&/shader|webgl|three/i.test(m.text()))errors.push(m.text());});
 await page.addInitScript(()=>{const Native=window.WebSocket;window.__packets=[];window.WebSocket=class extends Native{constructor(...a){super(...a);if(this.url.includes('/sync')){window.__socket=this;this.addEventListener('message',e=>{try{window.__packets.push(JSON.parse(e.data))}catch{}});}}};});
 const send=cmd=>page.evaluate(cmd=>window.__socket.send(JSON.stringify(cmd)),cmd);
 const shot=async(name)=>{const p=join(out,name+'.jpg');await page.screenshot({path:p,type:'jpeg',quality:75,timeout:15000});const b64=readFileSync(p).toString('base64');for(let i=0;i<b64.length;i+=6000)console.log('CARQA_IMAGE '+name+' '+(i/6000)+' '+b64.slice(i,i+6000));};
 await page.goto('http://127.0.0.1:'+server.port+'/?cameraQA=1',{waitUntil:'domcontentloaded',timeout:60000});
 await page.locator('.enter-button').waitFor({timeout:60000});await page.waitForFunction(()=>!document.querySelector('.enter-button')?.disabled,undefined,{timeout:70000});
 await page.locator('[data-role=vlad]').first().click();await page.locator('.enter-button').click();await page.locator('#auth').waitFor({state:'hidden',timeout:30000});
 if(mode==='lake'){
   await send({type:'lake_trip',pass:'day'});
   await page.waitForFunction(()=>window.__packets.some(p=>p.type==='world_event'&&p.message.includes('Предложение отправлено')));
   buddy.send(JSON.stringify({type:'lake_trip',pass:'day'}));
 }else await send({type:'car_travel',place:'market'});
 await page.locator('#car-ride').waitFor({state:'visible',timeout:10000});
 await page.waitForFunction(()=>Number(document.querySelector('.ride-track')?.getAttribute('aria-valuenow'))>=12);
 await shot('01-travel');
 await page.waitForFunction(()=>Number(document.querySelector('.ride-track')?.getAttribute('aria-valuenow'))>=49,undefined,{timeout:10000});
 await shot('01b-side');
 const ride=await page.evaluate(()=>window.__packets.findLast(p=>p.type==='snapshot'&&p.state.world.carRides?.vlad)?.state.world.carRides.vlad);
 assert.equal(ride.to,mode);assert.equal(ride.endsAt-ride.startedAt,mode==='lake'?10000:6000);
 const snapshot=buddyPackets.findLast(p=>p.type==='snapshot'&&p.state.world.carRides?.vlad);
 assert.ok(snapshot);if(mode==='lake')assert.deepEqual(snapshot.state.world.carRides.vlad,snapshot.state.world.carRides.alina);else assert.equal(snapshot.state.world.places.alina,'home');
 await page.locator('#car-ride').waitFor({state:'hidden',timeout:18000});
 assert.ok(await page.locator('#app').getAttribute('data-place')===mode);
 await shot('02-arrived');
 if(mode==='market'){
   await send({type:'approach',place:'market',station:'market-exit'});
   await page.waitForFunction(()=>window.__packets.some(p=>p.type==='world_path'&&p.role==='vlad'&&p.station==='market-exit'),undefined,{timeout:10000});
   await send({type:'travel',place:'district',via:'market-exit'});
   await page.locator('#car-ride').waitFor({state:'visible',timeout:10000});
   await page.waitForFunction(()=>Number(document.querySelector('.ride-track')?.getAttribute('aria-valuenow'))>=12);
   await shot('03-return');
   await page.locator('#car-ride').waitFor({state:'hidden',timeout:18000});
   assert.equal(await page.locator('#app').getAttribute('data-place'),'home');
 }
 assert.deepEqual(errors,[]);console.log('Car cinematic, shared timestamp, arrival and UI restored: '+mode);
}finally{await browser?.close();buddy?.terminate();await server?.close();rmSync(dir,{recursive:true,force:true});}
