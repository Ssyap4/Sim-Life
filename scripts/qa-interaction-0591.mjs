import {chromium} from 'playwright';
import {mkdtempSync,mkdirSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join,resolve} from 'node:path';
import assert from 'node:assert/strict';
import {initialState} from '../src/shared/protocol.ts';
import {stationById,approachFor} from '../src/shared/locations.ts';
import {addReadyFood} from '../src/shared/readyFood.ts';
import {openServerFiles} from '../server/storage.ts';
import {startServer} from '../server/server.ts';
const out='/tmp/simourhome-0591';mkdirSync(out,{recursive:true});
const dir=mkdtempSync(join(tmpdir(),'interaction-0591-'));let browser,server;
try{
 const s=initialState();s.money=100000;s.autonomy={vlad:'off',alina:'off'};
 s.pantry.eggs=3;s.meals.omelette=2;addReadyFood(s,'meal','omelette',2,'fridge');
 Object.assign(s.characters.vlad,approachFor(stationById('home','fridge'),'vlad'));
 openServerFiles(dir).save(s);
 server=await startServer({port:0,host:'127.0.0.1',dataDir:dir,distDir:resolve('dist'),testNoCodes:true,lifeClock:{now:()=>0,tickMs:600000}});
 browser=await chromium.launch({headless:true,args:['--enable-webgl','--enable-unsafe-swiftshader','--use-gl=angle','--use-angle=swiftshader','--disable-dev-shm-usage']});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{const Native=window.WebSocket;window.WebSocket=class extends Native{constructor(...a){super(...a);if(this.url.includes('/sync'))window.__socket=this;}};});
 const send=cmd=>page.evaluate(cmd=>window.__socket.send(JSON.stringify(cmd)),cmd);
 const panel=page.locator('#location-panel'),ready=panel.locator('[data-storage-page=ready]'),ingredients=panel.locator('[data-storage-page=ingredients]');
 const fit=async()=>assert.ok(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth+2));
 await page.goto('http://127.0.0.1:'+server.port+'/?cameraQA=1',{waitUntil:'domcontentloaded',timeout:60000});
 await page.waitForFunction(()=>!document.querySelector('.enter-button')?.disabled,undefined,{timeout:70000});
 await page.locator('.enter-button').click();await page.locator('#auth').waitFor({state:'hidden',timeout:30000});
 await send({type:'approach',place:'home',station:'fridge'});await ready.waitFor({timeout:45000});
 assert.equal(await panel.locator('.storage-food-card').count(),1);await fit();
 await page.screenshot({path:join(out,'01-fridge.jpg')});
 await ingredients.click();assert.equal(await ingredients.getAttribute('aria-pressed'),'true');assert.equal(await panel.locator('.storage-food-card').count(),0);
 await page.setViewportSize({width:320,height:568});await fit();await page.screenshot({path:join(out,'02-ingredients-320.jpg')});
 await ready.click();assert.equal(await panel.locator('.storage-food-card').count(),1);
 await panel.locator('.storage-food-card button').first().click();
 await page.waitForFunction(()=>document.querySelectorAll('#location-panel .storage-food-card').length===2,undefined,{timeout:15000});
 await panel.locator('.close-actions').click();
 await page.locator('#pets-btn').click();await page.locator('#actions .pet-tab').first().click();
 assert.equal(await page.locator('#actions .menu-section-label').count(),3);
 await page.screenshot({path:join(out,'03-pets-320.jpg')});
 assert.deepEqual(errors,[]);console.log('STORAGE AND PET UI OK');
}finally{await browser?.close();await server?.close();rmSync(dir,{recursive:true,force:true});}
